/**
 * 한국어 끝 조사 — **긴 것부터** 매칭한다("에서"를 "에"보다 먼저).
 * 한 글자 조사(이/가/도/만…)는 오탐이 있지만(고양이→고양) 지시서 규칙대로 두고,
 * 남는 어간이 2자 미만이면 떼지 않는 것으로 피해를 줄인다.
 */
const PARTICLES = [
  "에서부터", "으로부터", "이라는", "에게서", "한테서",
  "까지", "부터", "에서", "으로", "한테", "에게", "께서", "처럼", "보다", "이랑", "이나",
  "은", "는", "이", "가", "을", "를", "의", "에", "로", "와", "과", "도", "만", "랑",
].sort((a, b) => b.length - a.length);

export function stripKoreanParticle(word: string): string {
  for (const p of PARTICLES) {
    if (word.length - p.length >= 2 && word.endsWith(p)) return word.slice(0, -p.length);
  }
  return word;
}

